// Command sealfixture generates the cross-language E2EE interop fixture
// (docs/E2EE.md Phase F): it runs the REAL Go seal pipeline over a known
// message with a throwaway domain keypair and writes everything a JS test
// needs to prove client-side decryption opens Go-sealed mail.
//
// Regenerate (then commit the output) whenever the seal format changes:
//
//	cd mta && go run ./cmd/sealfixture ../ui/web/src/lib/__tests__/fixtures/sealed_v2_fixture.json
//
// It writes the current format (sealed_box_v2). sealed_fixture.json is frozen v1 mail.
package main

import (
	"crypto/rand"
	"encoding/base64"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"

	"golang.org/x/crypto/chacha20poly1305"
	"golang.org/x/crypto/nacl/box"

	"github.com/inbox2/mta/internal/seal"
)

type fixture struct {
	Note             string         `json:"note"`
	DomainPublicKey  string         `json:"domain_public_key"`
	DomainSecretKey  string         `json:"domain_secret_key"` // test-only!
	Sealed           map[string]any `json:"sealed"`
	Attachment       map[string]any `json:"attachment"`
	AttachmentCipher string         `json:"attachment_ciphertext"`
	Expected         map[string]any `json:"expected"`
}

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: sealfixture <output.json>")
		os.Exit(1)
	}

	pub, priv, err := box.GenerateKey(rand.Reader)
	must(err)

	const (
		domainID   = int64(4242)
		keyVersion = 3
		msgid      = "<fixture-1@interop.example>"
	)
	hmacKey := []byte("fixture-threading-key")
	msgidHmac := seal.ThreadingHMAC(hmacKey, msgid)
	aad := seal.AAD(domainID, keyVersion, msgidHmac)

	dek, err := seal.GenerateDEK()
	must(err)

	header := map[string]any{
		"subject":    "Interop: sealed across languages ✓",
		"from":       "Alice Interop <alice@interop.example>",
		"to":         "team@sealed.example",
		"snippet":    "This body proves Go-sealed mail opens in JS.",
		"message_id": msgid,
	}
	body := map[string]any{
		"plain": "This body proves Go-sealed mail opens in JS. Ünïcode too: 日本語.",
		"html":  "<p>This body proves Go-sealed mail opens in JS.</p>",
	}
	headerJSON, _ := json.Marshal(header)
	bodyJSON, _ := json.Marshal(body)

	headerNonce, headerCT, err := seal.Encrypt(dek, headerJSON, seal.PartAAD(aad, seal.RoleHeader))
	must(err)
	bodyNonce, bodyCT, err := seal.Encrypt(dek, bodyJSON, seal.PartAAD(aad, seal.RoleBody))
	must(err)
	sealedDEK, err := seal.SealDEK(dek, base64.StdEncoding.EncodeToString(pub[:]))
	must(err)

	// One attachment, index 0, mirroring sealer.sealAttachments AAD suffixes.
	attPlain := []byte("attachment-bytes: quarterly-figures")
	attAAD := append(append([]byte{}, aad...), []byte("|att:0")...)
	nameAAD := append(append([]byte{}, attAAD...), []byte("|name")...)
	attNonce, attCT, err := seal.Encrypt(dek, attPlain, attAAD)
	must(err)
	nameNonce, nameCT, err := seal.Encrypt(dek, []byte("figures-q3.xlsx"), nameAAD)
	must(err)

	// Sanity: the fixture must decrypt with its own keys before we write it.
	if _, e := seal.Decrypt(dek, headerNonce, headerCT, seal.PartAAD(aad, seal.RoleHeader)); e != nil {
		must(e)
	}
	if len(dek) != chacha20poly1305.KeySize {
		must(fmt.Errorf("bad dek size"))
	}

	fx := fixture{
		Note:            "Generated by mta/cmd/sealfixture — Go-sealed material for the JS interop test. Secret key is throwaway.",
		DomainPublicKey: base64.StdEncoding.EncodeToString(pub[:]),
		DomainSecretKey: base64.StdEncoding.EncodeToString(priv[:]),
		Sealed: map[string]any{
			"domain_key_version": keyVersion,
			"scheme":             "sealed_box_v2",
			"aad":                string(aad),
			"sealed_dek":         base64.StdEncoding.EncodeToString(sealedDEK),
			"body_nonce":         base64.StdEncoding.EncodeToString(bodyNonce),
			"body_ciphertext":    base64.StdEncoding.EncodeToString(bodyCT),
			"header_nonce":       base64.StdEncoding.EncodeToString(headerNonce),
			"header_ciphertext":  base64.StdEncoding.EncodeToString(headerCT),
		},
		Attachment: map[string]any{
			"sealed_filename": base64.StdEncoding.EncodeToString(nameCT),
			"filename_nonce":  base64.StdEncoding.EncodeToString(nameNonce),
			"content_nonce":   base64.StdEncoding.EncodeToString(attNonce),
			"content_type":    "application/vnd.ms-excel",
		},
		AttachmentCipher: base64.StdEncoding.EncodeToString(attCT),
		Expected: map[string]any{
			"header":              header,
			"body":                body,
			"attachment_plain":    string(attPlain),
			"attachment_filename": "figures-q3.xlsx",
		},
	}

	out, err := json.MarshalIndent(fx, "", "  ")
	must(err)
	must(os.MkdirAll(filepath.Dir(os.Args[1]), 0o755))
	must(os.WriteFile(os.Args[1], out, 0o644))
	fmt.Printf("wrote %s (%d bytes)\n", os.Args[1], len(out))
}

func must(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, "sealfixture:", err)
		os.Exit(1)
	}
}
