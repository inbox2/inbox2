#!/usr/bin/env node
// Convert a single-mesh GLB (Higgsfield/Meshy image-to-3D output) into an OBJ +
// its base-color texture, for iOS: SceneKit/ModelIO read OBJ natively but have
// never read glTF, and there's no GLB→USDZ converter on a stock Mac.
//
// Geometry only — no MTL. The app builds the material in Swift (SCNMaterial with
// the extracted texture), which dodges ModelIO's relative-path texture resolver
// and keeps the shading tweakable without regenerating the asset.
//
// Usage: node scripts/glb-to-obj.mjs in.glb out.obj [out-texture.png]
import { readFileSync, writeFileSync } from 'node:fs';

const [, , inPath, outPath, texPath] = process.argv;
if (!inPath || !outPath) {
  console.error('usage: glb-to-obj.mjs in.glb out.obj [out-texture.png]');
  process.exit(1);
}

const buf = readFileSync(inPath);
if (buf.readUInt32LE(0) !== 0x46546c67) throw new Error('not a GLB');
const jsonLen = buf.readUInt32LE(12);
const json = JSON.parse(buf.subarray(20, 20 + jsonLen).toString('utf8'));
const binStart = 20 + jsonLen + 8;
const bin = buf.subarray(binStart, binStart + buf.readUInt32LE(20 + jsonLen));

// glTF component type → the DataView reader for one element.
const READERS = {
  5120: ['getInt8', 1], 5121: ['getUint8', 1], 5122: ['getInt16', 2],
  5123: ['getUint16', 2], 5125: ['getUint32', 4], 5126: ['getFloat32', 4],
};
const COUNTS = { SCALAR: 1, VEC2: 2, VEC3: 3, VEC4: 4 };

/** Read accessor `i` as a flat array, honouring bufferView byteStride. */
function accessor(i) {
  if (i === undefined) return null;
  const acc = json.accessors[i];
  const [reader, size] = READERS[acc.componentType];
  const n = COUNTS[acc.type];
  const bv = json.bufferViews[acc.bufferView];
  const base = (bv.byteOffset || 0) + (acc.byteOffset || 0);
  const stride = bv.byteStride || size * n;
  const view = new DataView(bin.buffer, bin.byteOffset);
  const out = new Array(acc.count * n);
  for (let e = 0; e < acc.count; e++) {
    for (let c = 0; c < n; c++) {
      out[e * n + c] = view[reader](base + e * stride + c * size, true);
    }
  }
  return out;
}

// Every primitive of every mesh, welded into one OBJ object. (These models are
// one mesh in practice; the loop just avoids silently dropping a second one.)
const lines = [`# generated by glb-to-obj.mjs from ${inPath}`, 'o cube'];
let vBase = 1; // OBJ indices are 1-based and global across the file
for (const mesh of json.meshes || []) {
  for (const prim of mesh.primitives) {
    if (prim.mode !== undefined && prim.mode !== 4) continue; // triangles only
    const pos = accessor(prim.attributes.POSITION);
    const nor = accessor(prim.attributes.NORMAL);
    const uv = accessor(prim.attributes.TEXCOORD_0);
    const idx = accessor(prim.indices) || pos.map((_, i) => i / 3);

    for (let i = 0; i < pos.length; i += 3) {
      lines.push(`v ${pos[i]} ${pos[i + 1]} ${pos[i + 2]}`);
    }
    // glTF UVs are top-left origin, OBJ's are bottom-left — flip V.
    if (uv) for (let i = 0; i < uv.length; i += 2) lines.push(`vt ${uv[i]} ${1 - uv[i + 1]}`);
    if (nor) for (let i = 0; i < nor.length; i += 3) {
      lines.push(`vn ${nor[i]} ${nor[i + 1]} ${nor[i + 2]}`);
    }

    const ref = (v) => {
      const n = vBase + v;
      return `${n}/${uv ? n : ''}/${nor ? n : ''}`;
    };
    for (let i = 0; i < idx.length; i += 3) {
      lines.push(`f ${ref(idx[i])} ${ref(idx[i + 1])} ${ref(idx[i + 2])}`);
    }
    vBase += pos.length / 3;
  }
}
writeFileSync(outPath, lines.join('\n') + '\n');

// The base-color texture, straight out of the GLB's binary chunk (already PNG
// or JPEG — no re-encode).
if (texPath) {
  const mat = (json.materials || [])[0];
  const ti = mat?.pbrMetallicRoughness?.baseColorTexture?.index;
  if (ti === undefined) {
    console.warn('no baseColorTexture — skipping texture export');
  } else {
    const img = json.images[json.textures[ti].source];
    const bv = json.bufferViews[img.bufferView];
    const off = bv.byteOffset || 0;
    writeFileSync(texPath, bin.subarray(off, off + bv.byteLength));
    console.log(`texture → ${texPath} (${img.mimeType})`);
  }
}

console.log(`obj → ${outPath} (${vBase - 1} verts)`);
